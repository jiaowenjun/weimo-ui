import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

import ts from 'typescript'

const root = fileURLToPath(new URL('..', import.meta.url))
const checkOnly = process.argv.includes('--check')
const unknownArguments = process.argv.slice(2).filter((argument) => argument !== '--check')

if (unknownArguments.length > 0) {
  throw new Error(`Unknown arguments: ${unknownArguments.join(', ')}`)
}

function readProjectFile(relativePath) {
  const absolutePath = join(root, relativePath)

  if (!existsSync(absolutePath)) {
    throw new Error(`${relativePath} must exist.`)
  }

  return readFileSync(absolutePath, 'utf8')
}

function readProjectJson(relativePath) {
  return JSON.parse(readProjectFile(relativePath))
}

async function loadComponentManifest() {
  const relativePath = 'src/docs/components-manifest.ts'
  const source = readProjectFile(relativePath)
  const transpiled = ts.transpileModule(source, {
    compilerOptions: {
      module: ts.ModuleKind.ES2022,
      target: ts.ScriptTarget.ES2022,
      verbatimModuleSyntax: true,
    },
    fileName: relativePath,
  }).outputText
  const url = `data:text/javascript;charset=utf-8,${encodeURIComponent(transpiled)}`

  return import(url)
}

function propertyKey(id) {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(id) ? id : `'${id}'`
}

function definitionExportFor(id) {
  const relativePath = `src/docs/component-definitions/${id}.tsx`
  const source = readProjectFile(relativePath)
  const exports = [...source.matchAll(/^export const ([A-Za-z_$][A-Za-z0-9_$]*Definition)\s*=/gmu)]

  if (exports.length !== 1) {
    throw new Error(`${relativePath} must export exactly one component definition.`)
  }

  return exports[0][1]
}

function validateDefinitionFiles(componentManifest) {
  const componentIds = new Set(componentManifest.map((item) => item.id))
  const definitionFiles = readdirSync(join(root, 'src/docs/component-definitions'))
    .filter((file) => file.endsWith('.tsx'))
    .sort()

  for (const file of definitionFiles) {
    const source = readProjectFile(`src/docs/component-definitions/${file}`)
    const exportsDefinition =
      /^export const [A-Za-z_$][A-Za-z0-9_$]*Definition\s*=/mu.test(source)

    if (exportsDefinition && !componentIds.has(file.slice(0, -'.tsx'.length))) {
      throw new Error(`${file} exports a component definition but is missing from componentManifest.`)
    }
  }
}

function renderDefinitionsIndex(componentManifest) {
  const definitions = componentManifest.map((item) => ({
    exportName: definitionExportFor(item.id),
    id: item.id,
  }))
  const imports = definitions
    .map(({ exportName, id }) => `import { ${exportName} } from './${id}'`)
    .join('\n')
  const entries = definitions
    .map(({ exportName, id }) => `  ${propertyKey(id)}: ${exportName},`)
    .join('\n')

  return [
    '// Generated by scripts/sync-component-catalog.mjs. Do not edit directly.',
    imports,
    "import type { ComponentId } from '../components-manifest'",
    "import type { ComponentDefinition } from '../component-docs'",
    '',
    'export const componentDefinitionsById = {',
    entries,
    '} satisfies Record<ComponentId, ComponentDefinition>',
    '',
  ].join('\n')
}

function validateManifest(componentGroups, componentManifest, packageJson) {
  if (!Array.isArray(componentGroups) || !Array.isArray(componentManifest)) {
    throw new Error('components-manifest.ts must export componentGroups and componentManifest arrays.')
  }

  const groupIds = new Set(componentGroups.map((group) => group.id))
  const componentIds = new Set()
  const registryNames = new Set()

  for (const item of componentManifest) {
    if (componentIds.has(item.id)) {
      throw new Error(`Duplicate component id: ${item.id}`)
    }
    if (registryNames.has(item.registryName)) {
      throw new Error(`Duplicate component registry name: ${item.registryName}`)
    }
    if (!groupIds.has(item.group)) {
      throw new Error(`${item.id} uses unknown component group ${item.group}.`)
    }
    if (item.docs !== true || item.registry !== true) {
      throw new Error(`${item.id} must remain docs-enabled and registry-backed.`)
    }
    if (!packageJson.exports?.[item.packageExport]) {
      throw new Error(`${item.id} package export ${item.packageExport} must exist.`)
    }

    componentIds.add(item.id)
    registryNames.add(item.registryName)
  }

  return registryNames
}

function loadRegistryItems(componentManifest, publicRegistryNames) {
  const registryFiles = readdirSync(join(root, 'registry'))
    .filter((file) => file.endsWith('.json'))
    .sort()
  const itemsByName = new Map()

  for (const file of registryFiles) {
    const item = readProjectJson(`registry/${file}`)
    const fileName = file.slice(0, -'.json'.length)

    if (item.name !== fileName) {
      throw new Error(`registry/${file} must declare name ${fileName}.`)
    }
    if (itemsByName.has(item.name)) {
      throw new Error(`Duplicate standalone registry item: ${item.name}`)
    }

    itemsByName.set(item.name, item)
  }

  for (const item of componentManifest) {
    const registryItem = itemsByName.get(item.registryName)

    if (!registryItem) {
      throw new Error(`registry/${item.registryName}.json must exist.`)
    }
    if (registryItem.type !== 'registry:ui') {
      throw new Error(`Public component ${item.id} must use a registry:ui item.`)
    }
  }

  const internalItems = [...itemsByName.values()]
    .filter((item) => !publicRegistryNames.has(item.name))
    .sort((left, right) => {
      const typeOrder = { 'registry:lib': 0, 'registry:style': 1 }
      const leftOrder = typeOrder[left.type] ?? 2
      const rightOrder = typeOrder[right.type] ?? 2

      return leftOrder - rightOrder || left.name.localeCompare(right.name, 'en')
    })

  for (const item of internalItems) {
    if (item.type === 'registry:ui') {
      throw new Error(
        `Standalone registry:ui item ${item.name} must be listed in componentManifest.`,
      )
    }
  }

  return [
    ...internalItems,
    ...componentManifest.map((item) => itemsByName.get(item.registryName)),
  ]
}

function renderRootRegistry(registryConfig, registryItems) {
  if (Object.hasOwn(registryConfig, 'items')) {
    throw new Error('registry.config.json must not contain generated items.')
  }

  return `${JSON.stringify({ ...registryConfig, items: registryItems }, null, 2)}\n`
}

async function generatedArtifacts() {
  const { componentGroups, componentManifest } = await loadComponentManifest()
  const packageJson = readProjectJson('package.json')
  const publicRegistryNames = validateManifest(
    componentGroups,
    componentManifest,
    packageJson,
  )
  validateDefinitionFiles(componentManifest)
  const registryItems = loadRegistryItems(componentManifest, publicRegistryNames)
  const registryConfig = readProjectJson('registry.config.json')

  return new Map([
    [
      'src/docs/component-definitions/index.ts',
      renderDefinitionsIndex(componentManifest),
    ],
    ['registry.json', renderRootRegistry(registryConfig, registryItems)],
  ])
}

const staleArtifacts = []

for (const [relativePath, expected] of await generatedArtifacts()) {
  const absolutePath = join(root, relativePath)
  const current = existsSync(absolutePath) ? readFileSync(absolutePath, 'utf8') : null

  if (current === expected) continue

  if (checkOnly) {
    staleArtifacts.push(relative(root, absolutePath))
  } else {
    writeFileSync(absolutePath, expected)
    console.log(`updated ${relativePath}`)
  }
}

if (staleArtifacts.length > 0) {
  throw new Error(
    `Component catalog artifacts are stale: ${staleArtifacts.join(', ')}. Run pnpm catalog:sync.`,
  )
}
